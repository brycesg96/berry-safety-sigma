test('diseño adaptable sin desbordamiento y capturas de la primera pantalla', async ({ page }) => {
  await page.goto('./');
  for (const width of [360, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
  await page.evaluate(() => document.fonts.ready);
  await expect(page.getByText('Guardado en este navegador', { exact: true })).toBeVisible();
  await page.screenshot({ path: '/tmp/berry-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.locator('.sidebar').evaluate(el => el.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.screenshot({ path: '/tmp/berry-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Abrir menú' }).click();
  await expect.poll(() => page.locator('.sidebar').evaluate(el => Math.round(el.getBoundingClientRect().left))).toBe(0);
  await page.screenshot({ path: '/tmp/berry-mobile-menu.png' });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Abrir menú' })).toBeFocused();
});

test('Fecha de Cierre compartida una sola vez, nuevas observaciones y diseño compacto', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.goto('./'); await fillGeneral(page);
  await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  const add = page.getByRole('button', { name: 'Añadir observación', exact: true });
  await add.click(); await add.click(); await add.click();
  const cards = page.locator('.observation-card');
  const dates = page.getByLabel('Fecha de Cierre');
  for (let i = 0; i < 3; i++) await expect(dates.nth(i)).toHaveValue('');
  await dates.nth(1).fill('2026-11-15');
  for (let i = 0; i < 3; i++) await expect(dates.nth(i)).toHaveValue('2026-11-15');
  await dates.nth(0).fill('2026-11-20');
  await expect(dates.nth(1)).toHaveValue('2026-11-15');
  await expect(dates.nth(2)).toHaveValue('2026-11-15');
  await expect(page.getByText('Guardado en este navegador', { exact: true })).toBeVisible();
  await page.reload();
  await expect(dates.nth(0)).toHaveValue('2026-11-20');
  await add.click(); await expect(dates.nth(3)).toHaveValue('2026-11-15');
  await dates.nth(1).fill('');
  await expect(dates.nth(0)).toHaveValue('2026-11-20');
  await expect(dates.nth(2)).toHaveValue('2026-11-15');
  await expect(dates.nth(3)).toHaveValue('2026-11-15');
  const text = await cards.first().locator('.observation-texts').boundingBox();
  const detail = await cards.first().locator('.observation-details').boundingBox();
  expect(detail!.x).toBeGreaterThan(text!.x + text!.width);
  expect(Math.abs(detail!.y - text!.y)).toBeLessThan(2);
  expect((await cards.first().getByLabel('Descripción de la observación').boundingBox())!.height).toBeLessThanOrEqual(100);
  await cards.first().screenshot({ path: 'test-results/observation-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  const mobileText = await cards.first().locator('.observation-texts').boundingBox();
  const mobileDetail = await cards.first().locator('.observation-details').boundingBox();
  expect(mobileDetail!.y).toBeGreaterThan(mobileText!.y + mobileText!.height);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await cards.first().screenshot({ path: 'test-results/observation-mobile.png' });
});
